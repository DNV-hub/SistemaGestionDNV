  -- comparación sin mayúsculas/signos: "L=1,5M" ~ "L=1.5M" no se unifica a propósito
  create temp table edp_final (nombre text, id uuid) on commit drop;
  insert into edp_final (nombre, id)
  select f.nombre,
         (select e.id from public.nombres_edp e
           where upper(regexp_replace(e.nombre, '[^A-Za-z0-9/.]', '', 'g'))
               = upper(regexp_replace(f.nombre, '[^A-Za-z0-9/.]', '', 'g'))
           order by e.created_at limit 1)
  from finales f;

  insert into public.nombres_edp (nombre)
  select nombre from edp_final where id is null;

  update edp_final ef set id = e.id
  from public.nombres_edp e
  where ef.id is null and e.nombre = ef.nombre;

  if exists (select 1 from edp_final where id is null) then
    raise exception 'Quedaron nombres EDP sin id';
  end if;

  -- viejo -> nuevo (por id)
  create temp table id_map (viejo_id uuid, nuevo_id uuid) on commit drop;
  insert into id_map
  select e.id, ef.id
  from map_viejo mv
  join public.nombres_edp e on e.nombre = mv.viejo
  join edp_final ef on ef.nombre = mv.nuevo;

  update public.metrados_procura p set descripcion_edp_id = m.nuevo_id
  from id_map m where p.descripcion_edp_id = m.viejo_id and m.viejo_id <> m.nuevo_id;

  update public.alertas a set descripcion_edp_id = m.nuevo_id
  from id_map m where a.descripcion_edp_id = m.viejo_id and m.viejo_id <> m.nuevo_id;

  -- materiales: por su descripción (única)
  select count(*) into v_n from map_mat m left join public.materiales x on x.descripcion = m.descripcion where x.id is null;
  if v_n > 0 then raise exception 'Hay % materiales del mapa que no existen', v_n; end if;

  update public.materiales x set descripcion_edp_id = ef.id
  from map_mat m join edp_final ef on ef.nombre = m.nuevo
  where x.descripcion = m.descripcion;

  -- nombres reusados: dejan la escritura nueva
  update public.nombres_edp e set nombre = ef.nombre
  from edp_final ef where e.id = ef.id and e.nombre <> ef.nombre;

  -- guías
  insert into public.nombres_edp_guias (nombre_edp_id, descripcion)
  select distinct on (ef.id, upper(g.guia)) ef.id, g.guia
  from guias_tmp g join edp_final ef on ef.nombre = g.edp;

  -- nombres viejos que ya nadie usa
  delete from public.nombres_edp e
  where e.id not in (select id from edp_final)
    and not exists (select 1 from public.materiales x where x.descripcion_edp_id = e.id)
    and not exists (select 1 from public.metrados_procura p where p.descripcion_edp_id = e.id)
    and not exists (select 1 from public.alertas a where a.descripcion_edp_id = e.id);

  select count(*) into v_n from public.materiales where descripcion_edp_id is null;
  if v_n > 0 then raise exception 'Quedaron % materiales sin nombre EDP', v_n; end if;

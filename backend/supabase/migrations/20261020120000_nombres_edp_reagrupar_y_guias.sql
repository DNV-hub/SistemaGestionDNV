-- Reagrupa los nombres EDP con la lista nueva de Planeamiento y crea las
-- "descripciones por guía" (opciones para el ingreso y el catálogo).
--
-- No se borra a ciegas: los nombres viejos tienen Procura y alertas colgando.
-- Se crean/reusan los nombres nuevos, se pasan materiales, Procura y alertas, y
-- recién al final se borran los nombres viejos que quedaron sin uso.
-- Respaldo: tablas bak_*_20261020 (borrarlas cuando se confirme que todo está bien).
-- Reversión: restaurar descripcion_edp_id de materiales / metrados_procura / alertas
-- desde esas tablas y los nombres desde bak_nombres_edp_20261020.

create table public.nombres_edp_guias (
  id uuid primary key default gen_random_uuid(),
  nombre_edp_id uuid not null references public.nombres_edp(id) on delete cascade,
  descripcion text not null,
  created_at timestamptz not null default now()
);
create unique index nombres_edp_guias_unica on public.nombres_edp_guias (nombre_edp_id, upper(descripcion));
create index nombres_edp_guias_busqueda on public.nombres_edp_guias (upper(descripcion));
alter table public.nombres_edp_guias enable row level security;
create policy nombres_edp_guias_select on public.nombres_edp_guias for select
  using (public.has_permission('catalogo.ver'));
create policy nombres_edp_guias_write on public.nombres_edp_guias for all
  using (public.has_permission('catalogo.crear') or public.has_permission('catalogo.editar'))
  with check (public.has_permission('catalogo.crear') or public.has_permission('catalogo.editar'));

